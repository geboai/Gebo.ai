package ai.gebo.architecture.agents.services;

public class NetworkOfAgentsException extends Exception {

	public NetworkOfAgentsException() {
		
	}

	public NetworkOfAgentsException(String message) {
		super(message);
		
	}

	public NetworkOfAgentsException(Throwable cause) {
		super(cause);
		
	}

	public NetworkOfAgentsException(String message, Throwable cause) {
		super(message, cause);
		
	}

	public NetworkOfAgentsException(String message, Throwable cause, boolean enableSuppression,
			boolean writableStackTrace) {
		super(message, cause, enableSuppression, writableStackTrace);
		
	}

}
