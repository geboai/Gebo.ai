#!/usr/bin/env bash
#
# build-sbom-images.sh — Build gebo.ai Docker images with SBOM attestations
#
# Generates CycloneDX SBOMs as OCI attestations attached to each image using
# docker buildx --sbom. The Maven-built SBOM (application.cdx.json) is also
# COPY'd into each image at /opt/gebo.ai/sbom.cdx.json as before, so the SBOM
# is available both as a standard BuildKit attestation (queryable via
# `docker buildx imagetools inspect`) and as an in-image file.
#
# Usage:
#   ./dockers/build-sbom-images.sh                    # build all 3 images
#   ./dockers/build-sbom-images.sh platform           # build only geboai/platform
#   ./dockers/build-sbom-images.sh gebo.ai            # build only geboai/gebo.ai
#   ./dockers/build-sbom-images.sh easyinstall        # build only geboai/easyinstall.gebo.ai
#
# Options:
#   --push        Push images + SBOM attestations to Docker Hub
#   --load        Load images into the local Docker daemon (single-platform only)
#   --platforms   Override platforms (default: linux/amd64,linux/arm64)
#
# Prerequisites:
#   - docker buildx enabled (docker buildx create --use --name sbom-builder)
#   - The monolith bootable+swagger jar built:
#       mvn clean install -DskipTests
#       mvn -f gebo.apps.parent/gebo.ai.app/pom.xml -P swagger-on package -DskipTests
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="1.0.2.1-SNAPSHOT"
PLATFORMS="linux/amd64,linux/arm64"
JAR="$REPO_ROOT/gebo.apps.parent/gebo.ai.app/target/gebo.ai.app-${VERSION}-bootable.jar"
SBOM="$REPO_ROOT/gebo.apps.parent/gebo.ai.app/target/classes/META-INF/sbom/application.cdx.json"

# Defaults
PUSH=false
LOAD=false
TARGET="${1:-all}"

# Parse args
while [[ $# -gt 0 ]]; do
  case "$1" in
    --push)      PUSH=true; shift ;;
    --load)      LOAD=true; shift ;;
    --platforms) PLATFORMS="$2"; shift 2 ;;
    platform|gebo.ai|easyinstall|all) TARGET="$1"; shift ;;
    *) echo "Unknown arg: $1"; exit 1 ;;
  esac
done

# Build action: --push for multiplatform, --load for single-platform local
ACTION=""
if [ "$PUSH" = true ]; then
  ACTION="--push"
elif [ "$LOAD" = true ]; then
  ACTION="--load"
  PLATFORMS="linux/amd64"
fi

if [ -z "$ACTION" ]; then
  echo "ERROR: specify --push or --load"
  exit 1
fi

# Verify artifacts exist for images that need them
check_artifacts() {
  if [ ! -f "$JAR" ]; then
    echo "ERROR: Bootable jar not found at $JAR"
    echo "Build it first:  mvn -f gebo.apps.parent/gebo.ai.app/pom.xml -P swagger-on package -DskipTests"
    exit 1
  fi
  if [ ! -f "$SBOM" ]; then
    echo "ERROR: SBOM not found at $SBOM"
    echo "It is generated by the cyclonedx-maven-plugin during the build."
    exit 1
  fi
}

build_platform() {
  echo "=== Building geboai/platform:2.5 with SBOM ($PLATFORMS) ==="
  docker buildx build \
    --platform "$PLATFORMS" \
    --sbom=true \
    -t geboai/platform:2.5 \
    $ACTION \
    "$REPO_ROOT/dockers/gebo.ai.platform"
}

build_gebo_ai() {
  check_artifacts
  echo "=== Building geboai/gebo.ai with SBOM ($PLATFORMS) ==="
  cp "$JAR" "$REPO_ROOT/dockers/gebo.ai/"
  cp "$SBOM" "$REPO_ROOT/dockers/gebo.ai/"
  docker buildx build \
    --platform "$PLATFORMS" \
    --sbom=true \
    -t geboai/gebo.ai \
    -t geboai/gebo.ai:${VERSION} \
    $ACTION \
    "$REPO_ROOT/dockers/gebo.ai"
}

build_easyinstall() {
  check_artifacts
  echo "=== Building geboai/easyinstall.gebo.ai with SBOM ($PLATFORMS) ==="
  cp "$JAR" "$REPO_ROOT/dockers/easyinstall.gebo.ai/"
  cp "$SBOM" "$REPO_ROOT/dockers/easyinstall.gebo.ai/"
  docker buildx build \
    --platform "$PLATFORMS" \
    --sbom=true \
    -t geboai/easyinstall.gebo.ai \
    -t geboai/easyinstall.gebo.ai:${VERSION} \
    $ACTION \
    "$REPO_ROOT/dockers/easyinstall.gebo.ai"
}

case "$TARGET" in
  platform)    build_platform ;;
  gebo.ai)     build_gebo_ai ;;
  easyinstall) build_easyinstall ;;
  all)
    build_platform
    build_gebo_ai
    build_easyinstall
    ;;
  *)
    echo "Unknown target: $TARGET (use: platform, gebo.ai, easyinstall, or all)"
    exit 1
    ;;
esac

echo "=== Done ==="
echo ""
echo "Inspect SBOM attestations with:"
echo "  docker buildx imagetools inspect geboai/gebo.ai:${VERSION} --format json"
